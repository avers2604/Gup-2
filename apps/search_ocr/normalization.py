"""Нормализация терминов тезауруса — дословно meta.normalization из
docs/thesaurus/thesaurus_v0.9_draft.json: "Нормализация применяется к
short_forms и synonyms при построении словаря расширения запроса.
Каноническая форма сохраняется в исходном виде."

Общий модуль, а не метод в services.py/models.py/search.py по отдельности:
одно и то же правило нужно в трёх местах (проверки TH-02/TH-03 при
импорте, ключ upsert ThesaurusAmbiguity.abbr_normalized, сопоставление
токенов запроса в search.py) — дублирование правила по трём файлам было
бы риском дрейфа, тем более заметным, что цена ошибки здесь — то, что
пользователь не находит документ по «привычной» аббревиатуре."""
_STRIP_CHARS = ("«", "»", '"', "№", ".", ",")


def normalize_term(text: str) -> str:
    if text is None:
        return ""
    result = text.strip().lower()
    for ch in _STRIP_CHARS:
        result = result.replace(ch, "")
    # "  " (двойной пробел) в meta.normalization.strip_chars — по смыслу
    # схлопывание повторяющихся пробелов (в т.ч. появившихся после удаления
    # символов выше), не буквальное удаление пробела как символа (иначе
    # многословные термины типа "трамвайный парк" потеряли бы разделитель).
    return " ".join(result.split())
