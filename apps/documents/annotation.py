"""Автосборка аннотации НРД — «о чём документ» из распознанного текста.

ЧЕСТНАЯ ГРАНИЦА, которую важно понимать до чтения кода: это
ИЗВЛЕКАЮЩИЙ, а не порождающий сборщик. Он не понимает документ и не
пересказывает его своими словами — он находит в тексте те фрагменты,
которые в российских НРД по устоявшейся практике и содержат суть, и
склеивает их. Языковой модели в контуре нет и не предполагается:
система работает в закрытом контуре предприятия, а отправлять тексты
НРД (в том числе ДСП) во внешний сервис нельзя.

Из чего это следует практически: аннотация получается точной там, где
документ оформлен по правилам, и бесполезной там, где он оформлен как
попало. Поэтому она НИКОГДА не затирает аннотацию, написанную
человеком, и всегда помечена в интерфейсе как собранная автоматически —
чтобы методист видел, что её стоит прочитать, а не принял за свою.

На что опирается разбор. Распорядительный документ (приказ,
распоряжение) устроен так:

    СПб ГУП «Горэлектротранс»          <- служебная шапка
    ПРИКАЗ
    15.01.2024                № 301-п
    О внесении изменений в ...          <- заголовок
    В целях повышения безопасности ...  <- ЦЕЛЬ (нужна)
    ПРИКАЗЫВАЮ:
    1. Утвердить Инструкцию ...         <- ПЕРВОЕ РАСПОРЯЖЕНИЕ (нужно)
    2. Контроль за исполнением ...      <- дежурный пункт, не нужен

Нормативный (положение, инструкция, регламент, стандарт) — иначе:

    1. Общие положения
    1.1. Настоящее Положение устанавливает порядок ...  <- СУТЬ

Отсюда два пути разбора и общий запасной: первые осмысленные
предложения.
"""
import re

#: Предел длины. 400 знаков — примерно пять строк в карточке: столько
#: читают, не пролистывая. Обрезка идёт по границе предложения, а не по
#: символу: аннотация, оборванная на полуслове, хуже короткой.
MAX_LENGTH = 400

#: Минимальная длина фрагмента, который вообще считается предложением.
#: Отсекает обломки разбора («1.», «№ 301-п», «г. Санкт-Петербург»),
#: которые OCR возвращает отдельными строками.
MIN_SENTENCE = 25

#: Начало целевой части распорядительного документа.
_PURPOSE_OPENERS = (
    "в целях",
    "во исполнение",
    "на основании",
    "в связи с",
    "в соответствии с",
)

#: Распорядительное слово: после него идёт существо приказа.
_ORDER_MARKERS = ("приказываю", "распоряжаюсь", "постановляю", "решил")

#: Начало нормативного документа, определяющего сам себя.
_SELF_DEFINITION = re.compile(
    r"настоящ(?:ее|ая|ий)\s+\S+\s+(?:устанавливает|определяет|регламентирует|"
    r"вводит|распространяется|разработан[оаы]?)",
    re.IGNORECASE,
)

#: Дежурные пункты, которые сути не несут и в аннотацию не попадают.
#: «Контроль за исполнением оставляю за собой» есть в каждом втором
#: приказе и не отличает один документ от другого ничем.
_BOILERPLATE = re.compile(
    r"^\s*(?:контроль\s+за\s+исполнением"
    r"|настоящий\s+(?:приказ|документ)\s+вступает\s+в\s+силу"
    r"|признать\s+утратившим\s+силу\s*$"
    r"|с\s+приказом\s+ознакомить)",
    re.IGNORECASE,
)

#: Строки служебной шапки: реквизиты, а не содержание.
_HEADER_LINE = re.compile(
    r"^\s*(?:спб\s+гуп|гуп\s|государственное\s+унитарное"
    r"|приказ\s*$|распоряжение\s*$|инструкция\s*$|положение\s*$"
    r"|№\s*\S+|г\.\s*санкт-петербург|санкт-петербург\s*$"
    r"|\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}\s*(?:№.*)?$"
    r"|утверждаю|утверждено|приложение\s*№?\s*\d*\s*$)",
    re.IGNORECASE,
)

#: Нумерация пункта в начале строки: «1.», «1.1.», «2.3.4.».
_CLAUSE_NUMBER = re.compile(r"^\s*\d+(?:\.\d+)*\.?\s*")

#: Конец предложения внутри одной строки. Точка с последующей заглавной
#: буквой — иначе «п. 4.2» и «т. д.» рвали бы текст на куски.
_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[А-ЯЁA-Z])")

#: Распорядительное слово в конце целевой части: «…, ПРИКАЗЫВАЮ:».
#: Отрезается — в аннотации оно лишнее, суть идёт следом.
_ORDER_TAIL = re.compile(
    r"[,\s]*(?:приказываю|распоряжаюсь|постановляю|решил)\s*:?\s*$",
    re.IGNORECASE,
)


def _clean_lines(text):
    """Строки без служебной шапки и без пустот.

    Разбор идёт построчно, а не по предложениям всего текста, и это
    важно: в НРД пункты разделены переводом строки, а точку в конце
    ставят не всегда. Первая редакция резала текст только по «точка +
    заглавная» — и склеивала заголовок документа с целевой частью в одно
    «предложение», из-за чего цель переставала находиться.
    """
    lines = []
    for raw in text.splitlines():
        line = " ".join(raw.split())
        if not line or _HEADER_LINE.match(line):
            continue
        lines.append(line)
    return lines


def _is_meaningful(sentence):
    return len(sentence) >= MIN_SENTENCE and not _BOILERPLATE.match(sentence)


def _sentences_of(line):
    """Предложения одной строки без номера пункта в начале."""
    result = []
    for part in _SENTENCE_SPLIT.split(line):
        sentence = _CLAUSE_NUMBER.sub("", " ".join(part.split()))
        if _is_meaningful(sentence):
            result.append(sentence)
    return result


def _order_marker_index(lines):
    """Номер строки с распорядительным словом, иначе -1."""
    for index, line in enumerate(lines):
        lowered = line.lower()
        if any(marker in lowered for marker in _ORDER_MARKERS):
            return index
    return -1


def _purpose(lines, order_index):
    """Целевая часть: от «В целях…» до распорядительного слова.

    Цель нередко занимает две-три строки — берутся все до слова
    «ПРИКАЗЫВАЮ», а само оно отрезается.
    """
    limit = order_index + 1 if order_index >= 0 else len(lines)
    for index, line in enumerate(lines[:limit]):
        if line.lower().startswith(_PURPOSE_OPENERS):
            chunk = " ".join(lines[index:limit])
            chunk = _ORDER_TAIL.sub("", chunk).strip(" ,;:")
            return chunk if len(chunk) >= MIN_SENTENCE else ""
    return ""


def _clause_at(lines, index):
    """Пункт целиком, начиная со строки index.

    Пункт нередко разбит переносом строки посреди фразы — распознанный
    скан ломает строки по ширине листа, а не по смыслу. Собираем строки,
    пока не начнётся следующий пункт (строка с номером) и пока
    предыдущая не закончилась точкой. Без этого «…в новой редакции
    согласно» обрывалось ровно на переносе.

    Возвращает пару (текст пункта, сколько строк он занял) — второе
    нужно вызывающему, чтобы шагать по списку строк, а не пересчитывать
    длину заново и не ошибиться в этом пересчёте.
    """
    chunk = [lines[index]]
    for line in lines[index + 1:]:
        if _CLAUSE_NUMBER.match(line) or chunk[-1].rstrip().endswith((".", "!", "?")):
            break
        chunk.append(line)
    return " ".join(chunk), len(chunk)


def _operative(lines, order_index):
    """Существо документа: первый содержательный пункт после
    распорядительного слова, а для нормативного документа — строка, в
    которой он определяет сам себя («Настоящее Положение устанавливает…»).
    """
    if order_index >= 0:
        for offset in range(order_index + 1, len(lines)):
            clause, _consumed = _clause_at(lines, offset)
            sentences = _sentences_of(clause)
            if sentences:
                return sentences[0]

    for offset, line in enumerate(lines):
        if _SELF_DEFINITION.search(line):
            clause, _consumed = _clause_at(lines, offset)
            sentences = _sentences_of(clause)
            if sentences:
                return sentences[0]
    return ""


def _join(parts):
    """Склейка частей в связный текст.

    Целевая часть обрывается там, где стояло «ПРИКАЗЫВАЮ», то есть без
    знака в конце, — и без этой точки получалось «…эксплуатации
    Утвердить Инструкцию», где две фразы слипаются в одну нечитаемую.
    """
    normalised = []
    for part in parts:
        part = part.strip()
        if part and not part.endswith((".", "!", "?", "…")):
            part += "."
        normalised.append(part)
    return " ".join(normalised)


def _trim(text):
    """Обрезка до MAX_LENGTH по границе предложения.

    Если ни одна граница в предел не укладывается, обрезаем по последнему
    пробелу и ставим многоточие: лучше честно оборванная фраза, чем
    слово, разрезанное пополам.
    """
    text = " ".join(text.split())
    if len(text) <= MAX_LENGTH:
        return text

    window = text[: MAX_LENGTH + 1]
    cut = max(window.rfind(". "), window.rfind("! "), window.rfind("? "))
    if cut > MAX_LENGTH // 3:
        return window[: cut + 1].strip()

    space = window.rfind(" ")
    return (window[:space] if space > 0 else window[:MAX_LENGTH]).strip() + "…"


def build_annotation(text: str) -> str:
    """Собрать аннотацию из распознанного текста. Пустая строка — не вышло.

    Пустая строка возвращается намеренно вместо «заглушки»: аннотация,
    собранная из мусора, вреднее отсутствующей — её прочитают и поверят.
    """
    if not text or not text.strip():
        return ""

    lines = _clean_lines(text)
    if not lines:
        return ""

    order_index = _order_marker_index(lines)
    parts = [
        part
        for part in (_purpose(lines, order_index), _operative(lines, order_index))
        if part
    ]

    if not parts:
        # Ни цели, ни распорядительной части не нашлось: документ оформлен
        # не по образцу. Берём первые содержательные предложения — это всё
        # ещё лучше пустоты, но именно поэтому аннотация и помечается
        # собранной автоматически.
        # Запасной путь тоже собирает строки в пункт: иначе фраза,
        # перенесённая по ширине листа, разрывалась на середине, и
        # _join() ставил точку посреди предложения — «…меняется
        # порядок. выдачи путевых листов».
        # Запасной путь тоже собирает строки в пункт: иначе фраза,
        # перенесённая по ширине листа, разрывалась на середине, и
        # _join() ставил точку посреди предложения — «…меняется
        # порядок. выдачи путевых листов».
        fallback = []
        index = 0
        while index < len(lines) and len(fallback) < 2:
            clause, consumed = _clause_at(lines, index)
            fallback.extend(_sentences_of(clause))
            index += consumed
        parts = fallback[:2]

    if not parts:
        return ""
    return _trim(_join(parts))
