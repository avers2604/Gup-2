"""Права на просмотр WORM-журнала аудита (ТЗ 4.7).

ОТКУДА ВЗЯТО. Журнал — инструмент контроля безопасности, поэтому доступ
к нему закреплён за Офицером ИБ и Администратором. Основание — STACK.md,
где Офицер ИБ описан как отдельная ветка полномочий («контроль
безопасности, а не придание документам юридической силы»), и `ROLE_PRIVILEGE_ORDER`,
где выше него только Администратор.

Намеренно НЕ включён Контролёр/Юрист: он выше Методиста по документам,
но журнал показывает в том числе действия его самого, и «проверяющий,
читающий журнал собственных действий» — это не разделение обязанностей.

**Требует подтверждения Заказчиком** — как и остальные матрицы прав в
проекте, это интерпретация, а не цитата из ТЗ.
"""
from __future__ import annotations


def can_view_audit_log(user) -> bool:
    if not getattr(user, "is_authenticated", False):
        return False
    if user.is_superuser:
        return True
    from apps.iam.models import User

    return user.role in {User.Role.SECURITY_OFFICER, User.Role.ADMINISTRATOR}
