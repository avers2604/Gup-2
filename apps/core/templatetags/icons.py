"""Иконки интерфейса — инлайновые SVG без внешних зависимостей.

Почему не библиотека иконок. Проект не имеет сборки фронтенда: ни npm,
ни бандлера, статика отдаётся как есть (см. STACK.md, раздел про слой
оформления). Подключать иконочный шрифт ради полутора десятков значков
означало бы тащить бинарный файл, который нечем проверить, и полагаться
на приватную область Unicode — там, где достаточно нескольких путей.

Почему инлайн, а не спрайт с <use>. Спрайт экономит байты при десятках
повторов одного значка; здесь повторов мало, зато у спрайта есть цена:
общий документ с id, который обязан существовать до первого <use>, и
ссылки, ломающиеся в <template> и в частичных ответах HTMX. Инлайн от
этого не зависит.

Почему значок описан примитивами, а не строкой разметки. Первая
редакция хранила готовый фрагмент SVG и вставляла его через mark_safe —
bandit справедливо пометил это находкой уровня medium (B308/B703), а
CI отклоняет medium. Дело не в формальности: строка разметки в
константе — это ровно та привычка, из-за которой потом в неё попадает
подставляемое значение. Здесь разметку целиком строит Django, а модуль
хранит только геометрию.

Все значки — штриховые, 24×24, с `currentColor`: цвет задаёт CSS
окружения, а не сам значок, поэтому один и тот же значок работает и на
тёмно-синем боковом меню, и на светлой карточке.
"""
from django.utils.html import format_html, format_html_join

from django import template

register = template.Library()


def _path(d):
    return ("path", {"d": d})


def _circle(cx, cy, r):
    return ("circle", {"cx": cx, "cy": cy, "r": r})


def _rect(x, y, width, height, rx):
    return ("rect", {"x": x, "y": y, "width": width, "height": height, "rx": rx})


