#: Значки, которые заливаются целиком, а не рисуются обводкой. Звезда —
#: единственный такой случай: «в избранном» читается заливкой, пустая
#: звезда — контуром, и это разные состояния одного значка.
FILLABLE = frozenset({"star"})


@register.simple_tag
def icon(name, filled=False):
    """Значок `name`. `filled=True` — залитый вариант (звезда «в избранном»).

    Значок декоративен: рядом с ним всегда есть подпись или aria-label у
    самой кнопки, поэтому здесь aria-hidden, а не role="img" с названием.
    Иначе скринридер прочитал бы каждый значок дважды.
    """
    elements = _ICONS.get(name)
    if elements is None:
        raise ValueError(
            f"Неизвестный значок {name!r}. Доступны: {', '.join(sorted(_ICONS))}"
        )
    if filled and name not in FILLABLE:
        raise ValueError(f"Значок {name!r} не имеет залитого варианта")

    body = format_html_join(
        "",
        "<{}{} />",
        (
            (tag, format_html_join("", ' {}="{}"', sorted(attrs.items())))
            for tag, attrs in elements
        ),
    )
    return format_html(
        '<svg class="icon" viewBox="0 0 24 24" width="20" height="20" fill="{}" '
        'stroke="currentColor" stroke-width="1.6" stroke-linecap="round" '
        'stroke-linejoin="round" aria-hidden="true" focusable="false">{}</svg>',
        "currentColor" if filled else "none",
        body,
    )
